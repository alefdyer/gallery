    private val prefs = context.getSharedPreferences(PREFS, Context.MODE_PRIVATE)

    fun categories(): List<StickerCategory> {
        val order = categoryOrder()
        val byId = DEFAULT_CATEGORIES.associateBy { it.id }
        val ordered = order.mapNotNull { byId[it] }
        val missing = DEFAULT_CATEGORIES.filter { it.id !in order.toSet() }
        return ordered + missing
    }

    fun categoryOrder(): List<String> {
        // Один раз сбрасываем старый сохранённый порядок под новый дефолт.
        if (prefs.getInt(KEY_ORDER_VERSION, 0) < ORDER_VERSION) {
            prefs.edit {
                remove(KEY_ORDER)
                putInt(KEY_ORDER_VERSION, ORDER_VERSION)
            }
        }
        val raw = prefs.getString(KEY_ORDER, null)
        if (raw.isNullOrBlank()) return DEFAULT_ORDER
        val saved = raw.split(',').filter { it.isNotBlank() }
        val missing = DEFAULT_ORDER.filter { it !in saved }
        return saved + missing
    }

    fun setCategoryOrder(ids: List<String>) {
        prefs.edit {
            putString(KEY_ORDER, ids.joinToString(","))
            putInt(KEY_ORDER_VERSION, ORDER_VERSION)
        }
    }

